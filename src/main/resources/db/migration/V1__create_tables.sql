CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    description TEXT
);

CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    description TEXT
);

CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    price INTEGER,
    thumbnail VARCHAR(500),
    weight INTEGER,
    description TEXT,
    discount INTEGER,
    total_price INTEGER,
    category_id INTEGER,
    inventory_quantity INTEGER,
    sold_quantity INTEGER,
    created_at TIMESTAMP,
    deleted_at TIMESTAMP,
    edited_at TIMESTAMP,
    is_deleted BOOLEAN DEFAULT FALSE,

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
);

CREATE TABLE IF NOT EXISTS images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER,
    path VARCHAR(500),
    alt VARCHAR(255),

    CONSTRAINT fk_images_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100),
    phone VARCHAR(20),
    email VARCHAR(255),
    password VARCHAR(255),
    avatar VARCHAR(500),
    role_id INTEGER,
    created_at TIMESTAMP,
    deleted_at TIMESTAMP,
    edited_at TIMESTAMP,

    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id)
        REFERENCES roles(id)
);

CREATE TABLE IF NOT EXISTS provinces (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) UNIQUE
);

CREATE TABLE IF NOT EXISTS wards (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    province_id INTEGER,

    CONSTRAINT fk_wards_province
        FOREIGN KEY (province_id)
        REFERENCES provinces(id)
);

CREATE TABLE IF NOT EXISTS receivers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname VARCHAR(255),
    phone VARCHAR(20),
    ward_id INTEGER,
    created_at TIMESTAMP,
    deleted_at TIMESTAMP,
    edited_at TIMESTAMP,

    CONSTRAINT fk_receivers_ward
        FOREIGN KEY (ward_id)
        REFERENCES wards(id)
);

CREATE TABLE IF NOT EXISTS statuses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    description TEXT
);

CREATE TABLE IF NOT EXISTS payment_statuses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    description TEXT
);

CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_status_id INTEGER,
    method VARCHAR(100),
    amount INTEGER,
    transaction_id VARCHAR(255),
    created_at TIMESTAMP,

    CONSTRAINT fk_payments_payment_status
        FOREIGN KEY (payment_status_id)
        REFERENCES payment_statuses(id)
);

CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_id INTEGER,
    user_id INTEGER,
    price NUMERIC(12, 2),
    total_price NUMERIC(12, 2),
    status_id INTEGER,
    payment_id INTEGER UNIQUE,
    created_at TIMESTAMP,
    deleted_at TIMESTAMP,
    edited_at TIMESTAMP,

    CONSTRAINT fk_orders_receiver
        FOREIGN KEY (receiver_id)
        REFERENCES receivers(id),

    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT fk_orders_status
        FOREIGN KEY (status_id)
        REFERENCES statuses(id),

    CONSTRAINT fk_orders_payment
        FOREIGN KEY (payment_id)
        REFERENCES payments(id)
);

CREATE TABLE IF NOT EXISTS order_details (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER,
    order_id INTEGER,
    price NUMERIC(12, 2),
    quantity INTEGER,
    total_price NUMERIC(12, 2),

    CONSTRAINT fk_order_details_product
        FOREIGN KEY (product_id)
        REFERENCES products(id),

    CONSTRAINT fk_order_details_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
);